insert into public.interview_questions (
  recruitment_id,
  question,
  description,
  sort_order,
  is_active
)
select
  recruitments.id,
  content.question,
  content.description,
  content.position,
  true
from public.recruitments
cross join question_content as content
where not exists (
  select 1
  from public.interview_questions as questions
  where questions.recruitment_id = recruitments.id
    and questions.is_active
    and questions.sort_order = content.position
);
